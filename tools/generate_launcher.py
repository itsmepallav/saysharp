def polygon(path, size, scale=1.0):
    """Sample this small M/L/C/Z path for high-resolution raster fallbacks."""
    tokens = re.findall(r"[MLCZ]|-?\d+(?:\.\d+)?", path)
    points, i, current = [], 0, (0, 0)
    while i < len(tokens):
        op = tokens[i]
        i += 1
        if op == 'Z':
            break
        count = 6 if op == 'C' else 2
        values = list(map(float, tokens[i:i + count]))
        i += count
        if op == 'C':
            x0, y0 = current
            x1, y1, x2, y2, x3, y3 = values
            for step in range(1, 33):
                t = step / 32
                u = 1 - t
                points.append((u**3*x0 + 3*u*u*t*x1 + 3*u*t*t*x2 + t**3*x3,
                               u**3*y0 + 3*u*u*t*y1 + 3*u*t*t*y2 + t**3*y3))
            current = (x3, y3)
        else:
            current = tuple(values)
            points.append(current)
    return [((54 + (x - 54)*scale)*size/108, (54 + (y - 54)*scale)*size/108) for x, y in points]


def raster(size, round_icon=False, full_bleed=False):
    resolution = size * 4
    image = Image.new('RGBA', (resolution, resolution), GREEN if full_bleed else (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    draw.polygon(polygon(CIRCLE if round_icon else SQUARE, resolution), fill=GREEN)
    draw.polygon(polygon(BUBBLE, resolution, 1.36), fill=IVORY)
    draw.polygon(polygon(LETTER, resolution, 1.36), fill=GREEN)
    return image.resize((size, size), Image.Resampling.LANCZOS)


