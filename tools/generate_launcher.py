def vector(background=None, legacy=False):
    base = '' if background is None else f'<path android:fillColor="{GREEN}" android:pathData="{background}" />'
    mark = f'<path android:fillColor="{IVORY}" android:fillType="evenOdd" android:pathData="{MARK}" />'
    if legacy:
        mark = '<group android:pivotX="54" android:pivotY="54" android:scaleX="1.36" android:scaleY="1.36">' + mark + '</group>'
    size = 48 if legacy else 108
    return f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp" android:height="{size}dp" android:viewportWidth="108" android:viewportHeight="108">
    {base}
    {mark}
</vector>
'''


SQUARE = "M26,4 L82,4 C96,4 104,12 104,26 L104,82 C104,96 96,104 82,104 L26,104 C12,104 4,96 4,82 L4,26 C4,12 12,4 26,4 Z"
CIRCLE = "M54,4 C81.614,4 104,26.386 104,54 C104,81.614 81.614,104 54,104 C26.386,104 4,81.614 4,54 C4,26.386 26.386,4 54,4 Z"
